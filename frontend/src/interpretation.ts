export async function enrichInterpretation(result: AssessmentResult, answers: Record<number, boolean>): Promise<ResultInterpretation> {
  const fallback = buildLocalInterpretation(result);
  const controller = new AbortController();
  const timeout = window.setTimeout(() => controller.abort(), 22000);
  try {
    const response = await fetch("/api/interpretations", {
      method: "POST",
      headers: { "Content-Type":"application/json" },
      body: JSON.stringify({
        answers: Object.entries(answers).map(([questionId, value]) => ({ questionId:Number(questionId), value })),
        scales:result.scales,
        intelligences:result.intelligences ?? [],
      }),
      signal: controller.signal,
    });
    if (!response.ok) return fallback;
    return { ...await response.json() as ResultInterpretation, source:"openai" };
  } catch {
    return fallback;
  } finally {
    window.clearTimeout(timeout);
  }
}
